#!/usr/bin/env python3
"""Regenerates src/AiO.Core/Razer/RazerDeviceCatalog.g.cs from OpenRazer's driver headers.

Usage:
    mkdir -p /tmp/openrazer && cd /tmp/openrazer
    for f in razermouse_driver.h razerkbd_driver.h razerkraken_driver.h razeraccessory_driver.h; do
        curl -sSfLO https://raw.githubusercontent.com/openrazer/openrazer/master/driver/$f
    done
    python3 tools/gen_razer_catalog.py /tmp/openrazer > src/AiO.Core/Razer/RazerDeviceCatalog.g.cs
"""
import re, sys
ref = sys.argv[1]
files = [("razermouse_driver.h","Mouse"),("razerkbd_driver.h","Keyboard"),("razerkraken_driver.h","Headset"),("razeraccessory_driver.h","Accessory")]
special = {"V2":"V2","V3":"V3","PRO":"Pro","HS":"HS","TE":"TE","ESL":"ESL","RGB":"RGB","FPS":"FPS","MMO":"MMO","HDK":"HDK","LED":"LED","USB":"USB","SE":"SE","X":"X","ARGB":"ARGB","DOCK":"Dock","JP":"JP","UK":"UK","US":"US","ISO":"ISO","ANSI":"ANSI","TKL":"TKL","HYPERSPEED":"HyperSpeed","DEATHADDER":"DeathAdder","BLACKWIDOW":"BlackWidow","DEATHSTALKER":"DeathStalker","ORNATA":"Ornata","CYNOSA":"Cynosa","HUNTSMAN":"Huntsman","BASILISK":"Basilisk","LANCEHEAD":"Lancehead","MAMBA":"Mamba","NAGA":"Naga","VIPER":"Viper","OROCHI":"Orochi","ABYSSUS":"Abyssus","IMPERATOR":"Imperator","OUROBOROS":"Ouroboros","TAIPAN":"Taipan","DIAMONDBACK":"Diamondback","ATHERIS":"Atheris","COBRA":"Cobra","FIREFLY":"Firefly","GOLIATHUS":"Goliathus","KRAKEN":"Kraken","CHROMA":"Chroma","WIRELESS":"Wireless","WIRED":"Wired","RECEIVER":"Receiver","BLADE":"Blade","STEALTH":"Stealth","ULTIMATE":"Ultimate","MINI":"Mini","ELITE":"Elite","ESSENTIAL":"Essential","TOURNAMENT":"Tournament","EDITION":"Edition","MERCURY":"Mercury","QUARTZ":"Quartz","WHITE":"White","PINK":"Pink"}
def nice(tok):
    t = tok.upper()
    if t in special: return special[t]
    if re.fullmatch(r"\d+", t): return t
    if re.search(r"\d", t): return t
    return t.capitalize()
seen = {}
for fn, kind in files:
    for line in open(f"{ref}/{fn}"):
        m = re.match(r"#define USB_DEVICE_ID_RAZER_(\w+)\s+0x([0-9A-Fa-f]+)", line)
        if not m: continue
        name, pid = m.group(1), int(m.group(2),16)
        if pid in seen: continue
        name = name.replace("3_5G","3.5G")
        words = " ".join(nice(w) for w in name.split("_") if w)
        seen[pid] = (kind, words)
print("// <auto-generated>")
print("// Product ids collected from the OpenRazer project's public device list")
print("// (https://github.com/openrazer/openrazer). Regenerate with tools/gen_razer_catalog.py.")
print("// </auto-generated>")
print("namespace AiO.Core.Razer;\n")
print("public static partial class RazerDeviceCatalog\n{")
print("    private static readonly Dictionary<ushort, (RazerDeviceType Type, string Name)> Known = new()\n    {")
for pid in sorted(seen):
    kind, words = seen[pid]
    print(f'        [0x{pid:04X}] = (RazerDeviceType.{kind}, "Razer {words}"),')
print("    };\n}")
